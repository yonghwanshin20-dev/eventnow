import type { RegionCode } from "@/data/regions";

export type { RegionCode };

/** Event category — matches events.category CHECK constraint */
export type EventCategory =
  | "popup"
  | "exhibition"
  | "festival"
  | "kids_experience"
  /** 언제든 가 볼 만한 장소 — 유적지·문화재·관광지·자연경관·박물관·미술관 */
  | "attraction";

/** Target age group for family-friendly filtering */
export type TargetAgeGroup = "all" | "toddler" | "kids" | "elementary";

/** Event lifecycle status (화면에서는 날짜로 다시 계산한다) */
export type EventStatus = "upcoming" | "ongoing" | "ended";

/** 장소·나들이 유형 필터 (상단 통합 필터용) */
export type PlaceType =
  | "historical"
  | "nature_science"
  | "amusement_park"
  | "park_playground"
  | "forest_recreation"
  | "cultural_center"
  | "temple";

/** Amenities stored in events.amenities JSONB */
export interface EventAmenities {
  parking: boolean;
  stroller: boolean;
  nursing_room: boolean;
}

/**
 * Full event row as stored in Supabase `events` table (PRD §4).
 * Date columns are ISO date strings (`YYYY-MM-DD`) from Postgres DATE.
 */
export interface Event {
  id: string;
  title: string;
  category: EventCategory;
  description: string | null;

  start_date: string;
  end_date: string;

  location_name: string;
  address: string;
  latitude: number | null;
  longitude: number | null;

  /** 특별시·광역시·도 */
  region: RegionCode;
  /** 구·군·시 (모르면 null) */
  district: string | null;
  /** 동·읍·면 (주소 또는 좌표로 확인된 것만, 모르면 없음) */
  dong?: string | null;

  is_family_friendly: boolean;
  target_age_group: TargetAgeGroup | null;
  /** 본문에 적힌 세부 대상 나이 (만 나이, 년) — "5~7세"면 5·7, "36개월 이상"이면 3·null */
  age_min?: number | null;
  age_max?: number | null;
  amenities: EventAmenities;

  booking_required: boolean;
  price_info: string | null;
  thumbnail_url: string | null;
  official_link: string | null;

  tags: string[] | null;
  /** 장소 성격 (상단 필터와 동일 축) */
  place_types?: PlaceType[] | null;
  status: EventStatus;

  /** 수집 출처 (tour_api, seoul, popup_scraper, seed_json …) */
  source?: string | null;
  /** events.json 시절 ID (evt-xxxx) — 옛 링크 리다이렉트용 */
  legacy_id?: string | null;

  created_at: string;
  updated_at: string;
}

/** Payload for inserting a new event (id / timestamps / defaults generated by DB) */
export type EventInsert = Omit<
  Event,
  | "id"
  | "created_at"
  | "updated_at"
  | "is_family_friendly"
  | "amenities"
  | "booking_required"
  | "status"
  | "description"
  | "latitude"
  | "longitude"
  | "target_age_group"
  | "price_info"
  | "thumbnail_url"
  | "official_link"
  | "tags"
  | "district"
> & {
  id?: string;
  description?: string | null;
  latitude?: number | null;
  longitude?: number | null;
  district?: string | null;
  is_family_friendly?: boolean;
  target_age_group?: TargetAgeGroup | null;
  amenities?: EventAmenities;
  booking_required?: boolean;
  price_info?: string | null;
  thumbnail_url?: string | null;
  official_link?: string | null;
  tags?: string[] | null;
  status?: EventStatus;
  created_at?: string;
  updated_at?: string;
};

/** Partial payload for updating an existing event */
export type EventUpdate = Partial<EventInsert>;

/** 목록 카드에 필요한 필드만 (클라이언트 전송량 축소) */
export type EventListItem = Pick<
  Event,
  | "id"
  | "title"
  | "category"
  | "start_date"
  | "end_date"
  | "location_name"
  | "address"
  | "region"
  | "district"
  | "dong"
  | "is_family_friendly"
  | "target_age_group"
  | "age_min"
  | "age_max"
  | "booking_required"
  | "thumbnail_url"
  | "place_types"
  | "status"
  | "description"
  | "price_info"
  | "official_link"
  | "source"
> & {
  /** 가까운 순 정렬 시 km */
  distance_km?: number | null;
  /** 남은 기간 라벨 (서버에서 KST 기준 계산) */
  when: {
    text: string;
    tone: "urgent" | "soon" | "live" | "upcoming" | "always" | "approx" | "ended";
  };
  is_free: boolean;
  /** 상시 운영 장소인지 기간 한정 행사인지 */
  schedule: "permanent" | "limited";
  /** 카드 일정 문구 ("10.16 – 10.25" / "언제든 방문" / "10월 중 · 날짜 확인 필요") */
  date_text: string;
  /** [위도, 경도] — 지도에서 마커를 누르면 같은 데이터로 빠른 보기를 연다 */
  coords: [number, number] | null;
};

/** 지도 마커용 최소 필드 */
export interface EventMapPoint {
  id: string;
  title: string;
  category: EventCategory;
  start_date: string;
  end_date: string;
  latitude: number;
  longitude: number;
}
