# 전남·광주 통합 표기 — 화면은 기존 2개 광역을 유지하고 구 이름으로 나눈다
_JEONNAM_GWANGJU_ALIASES = ("전남광주통합특별시", "전남광주특별시", "전남광주")


def _city_bases() -> dict[str, str]:
    """시·군 이름(‘시/군’ 뗀 것) → 광역. 두 광역에 같은 이름이 있으면(고성군 등) 쓰지 않는다.

    '구'는 여러 도시에 같은 이름이 많아 넣지 않고, '광주'는 광주광역시·경기 광주시가 겹쳐 빠진다.
    """
    seen: dict[str, set[str]] = {}
    for region, names in SUBREGIONS_BY_REGION.items():
        for name in names:
            if name.endswith(("시", "군")) and len(name) >= 3:
                seen.setdefault(name[:-1], set()).add(region)
    return {base: next(iter(rs)) for base, rs in seen.items() if len(rs) == 1}


_CITY_BASES = _city_bases()
_CITY_BASES_BY_LENGTH = sorted(_CITY_BASES, key=len, reverse=True)


def detect_region(address: str | None) -> str | None:
    """주소 앞부분으로 광역을 판정. 본문 어딘가의 지명은 보지 않는다.

    "경기도 광주시" → 경기도 (광주광역시 아님), "전라북도" → 전북특별자치도.
    "전남광주통합특별시 북구" → 광주광역시, "전남광주통합특별시 화순군" → 전라남도.
    판정 불가 시 None (서울 기본값으로 떨어뜨리지 않음).
    """
    if not address:
        return None
    text = address.strip().lstrip("(").strip()
    for alias in _JEONNAM_GWANGJU_ALIASES:
        if text.startswith(alias):
            rest = set(_tokens(text[len(alias):]))
            if rest & set(SUBREGIONS_BY_REGION["광주광역시"]):
                return "광주광역시"
            return "전라남도"
    for alias in _ALIASES_BY_LENGTH:
        if text.startswith(alias):
            return _REGION_ALIASES[alias]
    # 광역 이름 없이 시·군으로 시작하는 주소: "전주 경기전", "순천부 읍성", "여수 돌산", "영암군청년센터"
    for base in _CITY_BASES_BY_LENGTH:
        if text.startswith(base):
            return _CITY_BASES[base]
    return None


def _tokens(address: str) -> list[str]:
    return [t for t in re.split(r"[\s,()]+", address) if t]


def detect_district(region: str | None, address: str | None) -> str | None:
    """광역 안에서 구/군/시를 토큰 단위로 정확히 매칭 (부산 '서구' ≠ '강서구')."""
    if not region or not address:
        return None
    names = SUBREGIONS_BY_REGION.get(region) or []
    if not names:
        return None
    tokens = set(_tokens(address))
    for name in sorted(names, key=len, reverse=True):
        if name in tokens:
            return name
    # "수원시팔달구"처럼 붙어 쓴 주소: 토큰이 이름으로 시작하는 경우
    for name in sorted(names, key=len, reverse=True):
        if any(tok.startswith(name) for tok in tokens):
            return name
    # "전주 경기전"처럼 시·군을 뗀 이름으로 시작하는 주소
    first = address.strip()
    for name in sorted(names, key=len, reverse=True):
        if name.endswith(("시", "군")) and len(name) >= 3 and first.startswith(name[:-1]):
            return name
    return None
