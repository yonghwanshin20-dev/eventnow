def to_event(c: dict, i: int) -> dict:
    return {
        "id": eid(c["title"], c["start"]),
        "title": c["title"],
        "category": "exhibition",
        "description": c["description"],
        "start_date": c["start"],
        "end_date": c["end"],
        "location_name": c["loc"],
        "address": c["addr"],
        "latitude": None,
        "longitude": None,
        "region": c["region"],
        "district": c.get("district"),
        "is_family_friendly": c["family"],
        "target_age_group": c.get("age"),
        "amenities": {
            "parking": c["parking"],
            "stroller": c["stroller"],
            "nursing_room": c["nursing"],
        },
        "booking_required": c["booking"],
        "price_info": c["price"],
        "thumbnail_url": THUMBS[i % len(THUMBS)],
        "official_link": c.get("link"),
        "tags": c["tags"],
        "status": status_for(c["start"], c["end"]),
        "created_at": "2026-07-28T00:00:00Z",
        "updated_at": "2026-07-28T00:00:00Z",
    }


def main() -> None:
    existing = json.loads(EVENTS_PATH.read_text(encoding="utf-8"))
    by_key = {(e["title"], e["start_date"]): e for e in existing}

    added = 0
    for i, c in enumerate(MUSEUMS):
        event = to_event(c, i)
        key = (event["title"], event["start_date"])
        if key not in by_key:
            added += 1
        by_key[key] = event

    final = list(by_key.values())
    rank = {"ongoing": 0, "upcoming": 1, "ended": 2}
    final.sort(key=lambda e: (rank.get(e["status"], 9), e["start_date"]))
    EVENTS_PATH.write_text(json.dumps(final, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"total={len(final)} added_or_updated_museums={added}")


if __name__ == "__main__":
    main()
