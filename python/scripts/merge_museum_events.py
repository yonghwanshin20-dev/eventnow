def eid(title: str, start: str) -> str:
    return f"evt-{hashlib.md5(f'{title}|{start}'.encode()).hexdigest()[:10]}"


def status_for(start: str, end: str) -> str:
    s = date.fromisoformat(start[:10])
    e = date.fromisoformat(end[:10])
    if e < TODAY:
        return "ended"
    if s > TODAY:
        return "upcoming"
    return "ongoing"


